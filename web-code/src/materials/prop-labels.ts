/** 把 camelCase / 点号路径属性名翻译成中文，格式为「中文（英文）」由调用方拼接。 */
export function translatePropName(name: string): string {
  const tokens = name
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1 $2')
    .split(/[.\s_-]+/)
    .filter(Boolean)
  const zh = tokens.map((token) => TOKEN_CN[token.toLowerCase()] ?? token).join('')
  return zh || name
}
