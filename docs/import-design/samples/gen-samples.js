function buildSheet(aoa, merges, colWidths) {
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  if (merges && merges.length) ws['!merges'] = merges.map(m => ({ s: { r: m.s.r, c: m.s.c }, e: { r: m.e.r, c: m.e.c } }));
  if (colWidths) ws['!cols'] = colWidths.map(w => ({ wch: w }));
  return ws;
}

